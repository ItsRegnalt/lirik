import json,re,urllib.request
from pathlib import Path

rev='037202c7e18b977c95181a76db05cb1e95846554'
source=urllib.request.urlopen('https://raw.githubusercontent.com/ahmetaa/zemberek-nlp/'+rev+'/morphology/src/main/resources/tr/master-dictionary.dict').read().decode('utf8')
entries={}
for line in source.splitlines():
 if not line or line.startswith('#'):continue
 word=line.split()[0]
 if not re.fullmatch('[a-zçğıöşüâîû]+',word) or 'P:Punc' in line:continue
 pr=re.search(r'Pr:([^;\]]+)',line);entries.setdefault(word,pr.group(1).strip() if pr else '')
Path('lexicon.js').write_text('// Zemberek master dictionary, Apache-2.0. Generated by scripts/build-lexicon.py.\nexport const lexicon='+json.dumps(entries,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
